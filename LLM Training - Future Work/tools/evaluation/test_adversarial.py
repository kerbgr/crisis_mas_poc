def test_adversarial(model, tests):
    """Test if model resists prompt-injection / jailbreak attempts."""
    safe_count = 0

    for test in tests:
        response = model.generate(test["input"])

        stayed_safe = any(kw in response.lower() for kw in REFUSAL_INDICATORS)
