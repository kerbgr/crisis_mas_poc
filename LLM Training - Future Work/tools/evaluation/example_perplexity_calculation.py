def calculate_perplexity(model_path, test_texts, base_tokenizer="meta-llama/Meta-Llama-3.1-8B-Instruct"):
    device = get_device()  # cuda > mps (Apple Silicon) > cpu

    model = AutoModelForCausalLM.from_pretrained(model_path).to(device)
    tokenizer = AutoTokenizer.from_pretrained(base_tokenizer)

    total_loss = 0
    for text in test_texts:
        inputs = tokenizer(text, return_tensors="pt").to(device)
        with torch.no_grad():
            outputs = model(**inputs, labels=inputs["input_ids"])
            total_loss += outputs.loss.item()

    perplexity = torch.exp(torch.tensor(total_loss / len(test_texts)))
    print(f"Perplexity: {perplexity:.2f}")
    return perplexity


