    acc_a = accuracy(model_output[group_a_mask], target[group_a_mask])
    acc_b = accuracy(model_output[group_b_mask], target[group_b_mask])

    # Fairness penalty (penalize large accuracy gaps). If either group is
    # absent from this batch there's nothing to compare -- skip the penalty
    # rather than crashing or silently treating a missing group as 0% accurate.
    if acc_a is None or acc_b is None:
        fairness_penalty = torch.tensor(0.0, device=model_output.device)
    else:
        fairness_penalty = torch.abs(acc_a - acc_b)

    # Combined loss
    total_loss = ce_loss + 0.1 * fairness_penalty

