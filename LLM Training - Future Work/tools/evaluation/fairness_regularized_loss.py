import torch
import torch.nn.functional as F


def accuracy(model_output, target):
    """Fraction of correct top-1 predictions. Returns None on an empty batch
    (a group with zero examples in this batch) rather than dividing by zero.
    """
    if target.numel() == 0:
        return None
    predictions = model_output.argmax(dim=-1)
    return (predictions == target).float().mean()


